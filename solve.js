// Fast drop-in for makefun-site 1.0.0: run(input) returns exactly the output
// tree makefun-site 1.0.0's build returns, byte for byte, but faster.
// Written from the behaviour stated in makefun-site's README and its
// reference code: same front matter, template dialect, Markdown subset,
// slug rule and report, reimplemented here as a single-pass renderer with
// cached slugs and a flat template-op interpreter. No dependencies.

const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

const RESERVED = ['posts', 'tags', 'page'];
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

// ------------------------------------------------------------------ text

const ESC_RE_G = /[&<>"']/g;
const ESCMAP = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

function esc(s) {
  return s.replace(ESC_RE_G, (c) => ESCMAP[c]);
}

const SLUG_MAX = 64;

function slugifyRaw(text) {
  let ascii = true;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) > 127) { ascii = false; break; }
  }
  if (ascii) {
    // NFKD is the identity on ASCII and ASCII holds no combining marks,
    // so the slug is the lowercased alnum runs joined by single '-'.
    let out = text.toLowerCase().replace(/[^a-z0-9]+/g, '-');
    let a = 0, b = out.length;
    while (a < b && out.charCodeAt(a) === 45) a++;
    while (b > a && out.charCodeAt(b - 1) === 45) b--;
    out = out.slice(a, b);
    if (out.length > SLUG_MAX) {
      out = out.slice(0, SLUG_MAX);
      let e = out.length;
      while (e > 0 && out.charCodeAt(e - 1) === 45) e--;
      out = out.slice(0, e);
    }
    return out === '' ? 'untitled' : out;
  }
  const plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
  let out = '';
  let gap = false;
  for (const ch of plain) {
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
  return out === '' ? 'untitled' : out;
}

// Per-case slug cache (created fresh in run, never shared across cases).
function slugify(text, cache) {
  const hit = cache.get(text);
  if (hit !== undefined) return hit;
  const v = slugifyRaw(text);
  cache.set(text, v);
  return v;
}

function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

function longDate(date) {
  const [y, m, d] = date.split('-');
  return `${Number(d)} ${MONTHS[Number(m) - 1]} ${y}`;
}

function resolvePath(dir, rel) {
  const parts = dir === '' ? [] : dir.split('/');
  for (const seg of rel.split('/')) {
    if (seg === '' || seg === '.') continue;
    if (seg === '..') {
      if (parts.length === 0) return null;
      parts.pop();
    } else parts.push(seg);
  }
  return parts.join('/');
}

const dirOf = (path) => (path.includes('/') ? path.slice(0, path.lastIndexOf('/')) : '');

// ------------------------------------------------------------- front matter

const KEYS = ['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary'];
const LINE_RE = /^([a-z_]+):(?: (.*))?$/;
const DATE_RE = /^(\d{4})-(\d{2})-(\d{2})$/;
const NAME_RE = /^[a-z0-9-]+$/;
const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const TAG_RE = /^[^"[\]]+$/;
const BLANK_RE = /^[ \t]*$/;

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return [4, 6, 9, 11].includes(m) ? 30 : 31;
}

function stringOf(raw) {
  if (raw.charCodeAt(0) === 34) {
    if (raw.length < 2 || !raw.endsWith('"')) return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw.charCodeAt(0) === 91) return { error: 'a bare string opens on [' };
  return { value: raw };
}

function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      const m = DATE_RE.exec(raw);
      const y = m ? Number(m[1]) : 0;
      const mo = m ? Number(m[2]) : 0;
      const d = m ? Number(m[3]) : 0;
      if (!m || y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      return { value: raw };
    }
    case 'tags': {
      if (!raw.startsWith('[') || !raw.endsWith(']')) return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      if (tags.some((t) => t === '' || !TAG_RE.test(t))) return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout':
      return NAME_RE.test(raw) ? { value: raw } : { error: 'key "layout": not a template name' };
    case 'slug':
      return SLUG_RE.test(raw) && raw.length <= 64 ? { value: raw } : { error: 'key "slug": not a slug' };
    default:
      return { error: `unknown key "${key}"` };
  }
}

// `lines` is the source split on '\n'. Returns { data, start } where start
// is the first body line, or { error }.
function parseFrontMatter(lines) {
  if (lines[0] !== '---') return { error: 'no front matter' };
  let close = -1;
  for (let i = 1; i < lines.length; i++) {
    if (lines[i] === '---') { close = i; break; }
  }
  if (close === -1) return { error: 'the front matter is not closed' };
  const data = {};
  for (let i = 1; i < close; i++) {
    const line = lines[i];
    if (BLANK_RE.test(line) || line.charCodeAt(0) === 35) continue;
    const m = LINE_RE.exec(line);
    if (!m) return { error: `line ${i + 1} is not "key: value"` };
    const key = m[1];
    const raw = (m[2] ?? '').replace(/[ \t]+$/, '');
    if (!KEYS.includes(key)) return { error: `unknown key "${key}"` };
    if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  return { data, start: close + 1 };
}

// ----------------------------------------------------------------- markdown

const FENCE_OPEN_RE = /^```([A-Za-z0-9_+-]*)[ \t]*$/;
const FENCE_CLOSE_RE = /^```[ \t]*$/;
const HEADING_RE = /^(#{1,6})[ \t]+(.*?)[ \t]*$/;
const HR_RE = /^(?:---|\*\*\*)[ \t]*$/;
const CONTINUED_RE = /^ {2,}\S/;
const WORD_RE = /\S+/g;
const WS_RE = /\s/;

function trimLine(line) {
  let a = 0, b = line.length;
  while (a < b && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return a === 0 && b === line.length ? line : line.slice(a, b);
}

function isBlank(line) {
  if (line === '') return true;
  const c = line.charCodeAt(0);
  if (c !== 32 && c !== 9) return false;
  return BLANK_RE.test(line);
}

function headingOf(line) {
  if (line.charCodeAt(0) !== 35) return null;
  const m = HEADING_RE.exec(line);
  return m === null || m[2] === '' ? null : { depth: m[1].length, text: m[2] };
}

function endsParagraph(line) {
  if (line === '') return true;
  const c = line.charCodeAt(0);
  if (c === 32 || c === 9) return BLANK_RE.test(line);
  if (c === 96) return FENCE_OPEN_RE.test(line);
  if (c === 35) return headingOf(line) !== null;
  if (c === 45 || c === 42) return HR_RE.test(line);
  return false;
}

// Ordered-list opener: { num, text } or null. Mirrors /^(\d{1,9})\. (.*)$/.
function orderedOf(line) {
  let j = 0;
  while (j < 9 && line.charCodeAt(j) >= 48 && line.charCodeAt(j) <= 57) j++;
  if (j === 0) return null;
  if (line.charCodeAt(j) !== 46 || line.charCodeAt(j + 1) !== 32) return null;
  return { num: Number(line.slice(0, j)), text: line.slice(j + 2) };
}

const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

// First index from `from` where `s` holds `what` outside a backslash escape,
// or -1. A match is escaped exactly when the run of backslashes directly
// before it (counted from `from`) is odd.
function findUnescaped(s, what, from) {
  let j = s.indexOf(what, from);
  while (j !== -1) {
    let k = j - 1, n = 0;
    while (k >= from && s[k] === '\\') { n++; k--; }
    if (n % 2 === 0) return j;
    j = s.indexOf(what, j + 1);
  }
  return -1;
}

// First single * from `from` (one whose run is not **), outside an escape.
function findSingleStar(s, from) {
  let j = s.indexOf('*', from);
  while (j !== -1) {
    let k = j - 1, n = 0;
    while (k >= from && s[k] === '\\') { n++; k--; }
    if (n % 2 === 1) { j = s.indexOf('*', j + 1); continue; }
    if (s[j + 1] === '*') { j = s.indexOf('*', j + 2); continue; }
    return j;
  }
  return -1;
}

function inline(s, link, slugCache) {
  const out = [];
  let i = 0;
  const len = s.length;
  while (i < len) {
    const j1 = s.indexOf('\\', i);
    const j2 = s.indexOf('`', i);
    const j3 = s.indexOf('*', i);
    const j4 = s.indexOf('[', i);
    let j = -1;
    if (j1 !== -1) j = j1;
    if (j2 !== -1 && (j === -1 || j2 < j)) j = j2;
    if (j3 !== -1 && (j === -1 || j3 < j)) j = j3;
    if (j4 !== -1 && (j === -1 || j4 < j)) j = j4;
    if (j === -1) {
      out.push(esc(s.slice(i)));
      break;
    }
    if (j > i) out.push(esc(s.slice(i, j)));
    const c = s[j];
    if (c === '\\') {
      if (j + 1 < len && ESCAPABLE.has(s[j + 1])) {
        out.push(esc(s[j + 1]));
        i = j + 2;
      } else {
        out.push('\\');
        i = j + 1;
      }
      continue;
    }
    if (c === '`') {
      const k = s.indexOf('`', j + 1);
      if (k > j + 1) {
        out.push(`<code>${esc(s.slice(j + 1, k))}</code>`);
        i = k + 1;
      } else {
        out.push('`');
        i = j + 1;
      }
      continue;
    }
    if (c === '*') {
      if (s[j + 1] === '*') {
        const k = findUnescaped(s, '**', j + 2);
        if (k > j + 2) {
          out.push(`<strong>${inline(s.slice(j + 2, k), link, slugCache)}</strong>`);
          i = k + 2;
        } else {
          out.push('**');
          i = j + 2;
        }
      } else {
        const k = findSingleStar(s, j + 1);
        if (k > j + 1) {
          out.push(`<em>${inline(s.slice(j + 1, k), link, slugCache)}</em>`);
          i = k + 1;
        } else {
          out.push('*');
          i = j + 1;
        }
      }
      continue;
    }
    // '['
    const k = findUnescaped(s, ']', j + 1);
    const m = k !== -1 && s[k + 1] === '(' ? s.indexOf(')', k + 2) : -1;
    const target = m === -1 ? '' : s.slice(k + 2, m);
    if (target !== '' && !WS_RE.test(target)) {
      out.push(`<a href="${esc(link(target))}">${inline(s.slice(j + 1, k), link, slugCache)}</a>`);
      i = m + 1;
    } else {
      out.push('[');
      i = j + 1;
    }
  }
  return out.join('');
}

// Renders body lines[start..] in one pass (no token array): { html, toc, excerpt }.
function renderMarkdown(lines, start, link, slugCache) {
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  let i = start;
  const n = lines.length;
  while (i < n) {
    const line = lines[i];
    if (isBlank(line)) { i++; continue; }
    if (line.charCodeAt(0) === 96 && line.charCodeAt(1) === 96 && line.charCodeAt(2) === 96) {
      const fm = FENCE_OPEN_RE.exec(line);
      if (fm !== null) {
        const lang = fm[1];
        const body = [];
        i++;
        while (i < n && !FENCE_CLOSE_RE.test(lines[i])) body.push(lines[i++]);
        i++;
        const cls = lang === '' ? '' : ` class="language-${esc(lang)}"`;
        const parts = ['<pre><code', cls, '>'];
        for (let k = 0; k < body.length; k++) { parts.push(esc(body[k]), '\n'); }
        parts.push('</code></pre>\n');
        blocks.push(parts.join(''));
        continue;
      }
    }
    const hd = headingOf(line);
    if (hd !== null) {
      const id = uniqueSlug(slugify(hd.text, slugCache), ids);
      const html = inline(hd.text, link, slugCache);
      blocks.push(`<h${hd.depth} id="${id}">${html}</h${hd.depth}>\n`);
      if (hd.depth === 2 || hd.depth === 3) toc.push({ level: hd.depth, id, html });
      i++;
      continue;
    }
    const c0 = line.charCodeAt(0);
    if ((c0 === 45 || c0 === 42) && HR_RE.test(line)) {
      blocks.push('<hr>\n');
      i++;
      continue;
    }
    if (c0 === 62) {
      const body = [];
      while (i < n && lines[i].charCodeAt(0) === 62) {
        const l = lines[i++];
        body.push(l.charCodeAt(1) === 32 ? l.slice(2) : l.slice(1));
      }
      const inner = body.map(trimLine).filter((l) => l !== '');
      blocks.push(inner.length === 0 ? '<blockquote>\n</blockquote>\n' : `<blockquote>\n<p>${inline(inner.join('\n'), link, slugCache)}</p>\n</blockquote>\n`);
      continue;
    }
    let isOrdered = false;
    let itemText = null;
    let startNum = 1;
    if ((c0 === 45 || c0 === 42) && line.charCodeAt(1) === 32) {
      itemText = line.slice(2);
    } else if (c0 >= 48 && c0 <= 57) {
      const od = orderedOf(line);
      if (od !== null) { isOrdered = true; startNum = od.num; itemText = od.text; }
    }
    if (itemText !== null) {
      const items = [[trimLine(itemText)]];
      i++;
      while (i < n) {
        const l2 = lines[i];
        if (isOrdered) {
          const od = l2.charCodeAt(0) >= 48 && l2.charCodeAt(0) <= 57 ? orderedOf(l2) : null;
          if (od !== null) { items.push([trimLine(od.text)]); i++; continue; }
        } else if ((l2.charCodeAt(0) === 45 || l2.charCodeAt(0) === 42) && l2.charCodeAt(1) === 32) {
          items.push([trimLine(l2.slice(2))]); i++; continue;
        }
        if (CONTINUED_RE.test(l2)) { items[items.length - 1].push(trimLine(l2)); i++; continue; }
        break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const open = isOrdered && startNum !== 1 ? `<ol start="${startNum}">` : `<${tag}>`;
      const parts = [open, '\n'];
      for (let k = 0; k < items.length; k++) {
        parts.push('<li>', inline(items[k].join('\n'), link, slugCache), '</li>\n');
      }
      parts.push(`</${tag}>\n`);
      blocks.push(parts.join(''));
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < n && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const html = inline(body.join('\n'), link, slugCache);
    if (excerpt === null) excerpt = html;
    blocks.push(`<p>${html}</p>\n`);
  }
  return { html: blocks.join(''), toc, excerpt: excerpt ?? '' };
}

